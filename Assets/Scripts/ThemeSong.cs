using UnityEngine;

public class ThemeSong : MonoBehaviour
{
    private static ThemeSong instance = null;

    private void Awake()
    {
        if (instance == null)
        {
            instance = this;
            DontDestroyOnLoad(gameObject);
        }
        else
        {
            Destroy(gameObject);
            return;
        }
    }
}
